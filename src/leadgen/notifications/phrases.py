class PhrasePicker:
    def __init__(self, store: Any | None = None, avoid_last: int = 5, rng: random.Random | None = None):
        self.store = store
        self.avoid_last = avoid_last
        self.rng = rng or random.Random()
        self._mem: dict[str, list[int]] = {}

    def _recent(self, cat: str) -> list[int]:
        if self.store is not None:
            return list(self.store.kv_get(f"phrases:{cat}", []))
        return self._mem.get(cat, [])

    def _save(self, cat: str, recent: list[int]) -> None:
        if self.store is not None:
            self.store.kv_set(f"phrases:{cat}", recent)
        else:
            self._mem[cat] = recent

    def pick(self, category: str) -> str:
        options = PHRASES[category]
        recent = self._recent(category)
        window = min(self.avoid_last, len(options) - 1)
        allowed = [i for i in range(len(options)) if i not in recent[-window:]] if window > 0 else list(range(len(options)))
        idx = self.rng.choice(allowed)
        self._save(category, (recent + [idx])[-20:])
        return options[idx]
